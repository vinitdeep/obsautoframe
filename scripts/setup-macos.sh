#!/usr/bin/env bash
# Prepares every third-party dependency needed to build V Media AI AutoFrame on macOS.
# Idempotent. Mirrors scripts/setup.ps1 (Windows). Creates third_party/ with:
#
#   obs-studio-<API>/         OBS headers the plugin is compiled against. libobs refuses plugins
#                             built with newer headers than the running OBS, so this is the OLDEST
#                             supported OBS (30.0 -> runs on 30..33+).
#   obs-sdk/include/obs/      those headers + a generated obsconfig.h
#   obs-mac/apple/OBS.app     official OBS <VER> for Apple silicon  (link + load test)
#   obs-mac/intel/OBS.app     official OBS <VER> for Intel          (link + load test)
#   obs-mac/universal/libobs.framework   arm64 + x86_64 libobs, to link one universal plugin
#   onnxruntime-osx-universal2-<ORT>/    ONNX Runtime (CPU + Core ML)
#   models/                   YOLOX-Nano / YOLOX-Tiny (Apache-2.0), SHA-256 verified
set -euo pipefail

OBS_API_VERSION="${OBS_API_VERSION:-30.0.0}"
OBS_VERSION="${OBS_VERSION:-33.0.1}"
ORT_VERSION="${ORT_VERSION:-1.23.2}"   # newest ONNX Runtime with a universal2 (arm64 + x86_64) build

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TP="$ROOT/third_party"
DL="$TP/dl"
mkdir -p "$TP" "$DL"

fetch() { # url dest
	[ -f "$2" ] && return 0
	echo "Downloading $1"
	curl -fL --retry 3 -o "$2.part" "$1"
	mv "$2.part" "$2"
}

# ------------------------------------------------------------------ OBS API headers
OBS_SRC="$TP/obs-studio-$OBS_API_VERSION"
if [ ! -f "$OBS_SRC/libobs/obs.h" ]; then
	echo "Fetching OBS Studio $OBS_API_VERSION headers (sparse)"
	rm -rf "$OBS_SRC"
	git clone --depth 1 --branch "$OBS_API_VERSION" --filter=blob:none --sparse \
		https://github.com/obsproject/obs-studio.git "$OBS_SRC"
	git -C "$OBS_SRC" sparse-checkout set libobs
fi
SDK_INC="$TP/obs-sdk/include/obs"
if [ ! -f "$SDK_INC/obs-module.h" ]; then
	mkdir -p "$SDK_INC"
	(cd "$OBS_SRC/libobs" && find . \( -name '*.h' -o -name '*.hpp' \) -print0 |
		while IFS= read -r -d '' h; do mkdir -p "$SDK_INC/$(dirname "$h")"; cp "$h" "$SDK_INC/$h"; done)
	# obsconfig.h is generated by OBS's CMake; values below match the macOS app bundle layout
	cat >"$SDK_INC/obsconfig.h" <<'EOF'
#pragma once
#define OBS_DATA_PATH "../Resources"
#define OBS_PLUGIN_PATH "../PlugIns"
#define OBS_PLUGIN_DESTINATION "PlugIns"
#define OBS_INSTALL_PREFIX ""
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
EOF
fi

# ------------------------------------------------------------------ OBS.app (Apple + Intel)
extract_obs_app() { # flavour(Apple|Intel) dest
	local flavour="$1" dest="$2"
	[ -d "$dest/OBS.app" ] && return 0
	local dmg="$DL/OBS-Studio-$OBS_VERSION-macOS-$flavour.dmg"
	fetch "https://github.com/obsproject/obs-studio/releases/download/$OBS_VERSION/OBS-Studio-$OBS_VERSION-macOS-$flavour.dmg" "$dmg"
	local mnt
	mnt="$(mktemp -d)"
	echo "Extracting OBS.app ($flavour)"
	hdiutil attach -nobrowse -readonly -noautoopen -mountpoint "$mnt" "$dmg" >/dev/null
	mkdir -p "$dest"
	ditto "$mnt/OBS.app" "$dest/OBS.app"
	hdiutil detach "$mnt" -quiet || hdiutil detach "$mnt" -force -quiet
	xattr -dr com.apple.quarantine "$dest/OBS.app" 2>/dev/null || true
}
extract_obs_app Apple "$TP/obs-mac/apple"
extract_obs_app Intel "$TP/obs-mac/intel"

# One universal libobs.framework (arm64 + x86_64) so a single build links both architectures.
UNI="$TP/obs-mac/universal"
if [ ! -d "$UNI/libobs.framework" ]; then
	mkdir -p "$UNI"
	ARM_FW="$TP/obs-mac/apple/OBS.app/Contents/Frameworks/libobs.framework"
	X86_FW="$TP/obs-mac/intel/OBS.app/Contents/Frameworks/libobs.framework"
	ditto "$ARM_FW" "$UNI/libobs.framework"
	rel="$(cd "$ARM_FW" && python3 -c 'import os;print(os.path.relpath(os.path.realpath("libobs")))')"
	lipo -create "$ARM_FW/$rel" "$X86_FW/$rel" -output "$UNI/libobs.framework/$rel"
	lipo -info "$UNI/libobs.framework/$rel"
fi

# ------------------------------------------------------------------ ONNX Runtime
ORT_DIR="$TP/onnxruntime-osx-universal2-$ORT_VERSION"
if [ ! -f "$ORT_DIR/include/onnxruntime_cxx_api.h" ]; then
	tgz="$DL/onnxruntime-osx-universal2-$ORT_VERSION.tgz"
	fetch "https://github.com/microsoft/onnxruntime/releases/download/v$ORT_VERSION/onnxruntime-osx-universal2-$ORT_VERSION.tgz" "$tgz"
	tar -xzf "$tgz" -C "$TP"
fi
lipo -info "$ORT_DIR/lib/libonnxruntime.$ORT_VERSION.dylib"

# ------------------------------------------------------------------ Models
MODELS="$TP/models"
mkdir -p "$MODELS"
get_model() { # file sha
	local dest="$MODELS/$1"
	fetch "https://github.com/Megvii-BaseDetection/YOLOX/releases/download/0.1.1rc0/$1" "$dest"
	local sha
	sha="$(shasum -a 256 "$dest" | cut -d' ' -f1)"
	if [ "$sha" != "$2" ]; then
		rm -f "$dest"
		echo "SHA-256 mismatch for $1 ($sha)" >&2
		exit 1
	fi
}
get_model yolox_nano.onnx c789161ed43c8269fcd4e67c67eeeb4e80c622da2eb296a20bc6007bd18a0b7d
get_model yolox_tiny.onnx 427cc366d34e27ff7a03e2899b5e3671425c262ea2291f88bb942bc1cc70b0f7
# Apache-2.0 requires the license text to travel with the models
fetch https://raw.githubusercontent.com/Megvii-BaseDetection/YOLOX/0.1.1rc0/LICENSE "$MODELS/YOLOX-LICENSE.txt"

echo
echo "Dependencies ready:"
echo "  OBS API headers  $SDK_INC  (OBS $OBS_API_VERSION)"
echo "  libobs           $UNI/libobs.framework  (OBS $OBS_VERSION, universal)"
echo "  ONNX Runtime     $ORT_DIR"
echo "  Models           $MODELS"
